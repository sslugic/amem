/**
 * Everything amem wrote outside its own data directory, and how to take it back out.
 * Each step only removes what amem added (its hook entries, its `amem` server, its
 * marked instruction block) and leaves the rest of a config file as it was.
 */
export type UninstallStep = { what: string; path: string; apply: () => void };

const BUNDLED_SKILLS = ["amem-bootstrap", "amem-update-working-memory", "amem-tasks", "amem-write-skill"];
const BEGIN = "<!-- BEGIN amem (generated) -->";
const END = "<!-- END amem -->";

function readJson(path: string): Record<string, unknown> | null {
  if (!existsSync(path)) return null;
  try {
    const parsed = JSON.parse(readFileSync(path, "utf8")) as unknown;
    return parsed && typeof parsed === "object" && !Array.isArray(parsed) ? (parsed as Record<string, unknown>) : null;
  } catch {
    // A file amem cannot parse is not one it will rewrite.
    return null;
  }
}

function writeJsonAtomic(path: string, value: unknown): void {
  const tmp = `${path}.amem-tmp-${process.pid}-${Date.now()}`;
  writeFileSync(tmp, `${JSON.stringify(value, null, 2)}\n`, "utf8");
  replaceFile(tmp, path);
}

/** A config with `<key>.amem` (mcpServers, context_servers): drop just that entry. */
function serverEntryStep(what: string, path: string, key = "mcpServers"): UninstallStep | null {
  const cfg = readJson(path);
  const servers = cfg?.[key] as Record<string, unknown> | undefined;
  if (!cfg || !servers || !("amem" in servers)) return null;
  return {
    what,
    path,
    apply: () => {
      const { amem: _drop, ...rest } = servers;
      writeJsonAtomic(path, { ...cfg, [key]: rest });
    },
  };
}

function isAmemCommand(command: string): boolean {
  return isAmemHookCommand(command) || /(amem(\.cmd|\.exe)?|cli\.js)"?\s+session touch/i.test(command);
}

function claudeHooksStep(): UninstallStep | null {
  const path = join(process.env.CLAUDE_HOME ?? join(homedir(), ".claude"), "settings.json");
  const cfg = readJson(path);
  const hooks = cfg?.hooks as Record<string, unknown[]> | undefined;
  if (!cfg || !hooks) return null;
  const cleaned: Record<string, unknown[]> = {};
  let found = false;
  for (const [event, rows] of Object.entries(hooks)) {
    const kept = (Array.isArray(rows) ? rows : []).filter((row) => {
      const cmds = ((row as { hooks?: Array<{ command?: string }> }).hooks ?? []).map((h) => h.command ?? "");
      const ours = cmds.length > 0 && cmds.every(isAmemCommand);
      if (ours) found = true;
      return !ours;
    });
    if (kept.length > 0) cleaned[event] = kept;
  }
  if (!found) return null;
  return { what: "Claude Code hooks", path, apply: () => writeJsonAtomic(path, { ...cfg, hooks: cleaned }) };
}

function cursorHooksStep(cursorHome: string): UninstallStep | null {
  const path = join(cursorHome, "hooks.json");
  const cfg = readJson(path);
  const hooks = cfg?.hooks as Record<string, unknown[]> | undefined;
  if (!cfg || !hooks) return null;
  const cleaned: Record<string, unknown[]> = {};
  let found = false;
  for (const [event, rows] of Object.entries(hooks)) {
    const kept = (Array.isArray(rows) ? rows : []).filter((row) => {
      const r = row as { command?: string; description?: string };
      const ours = (r.description ?? "").includes("Generated by amem") || isAmemCommand(r.command ?? "");
      if (ours) found = true;
      return !ours;
    });
    if (kept.length > 0) cleaned[event] = kept;
  }
  if (!found) return null;
  return { what: "Cursor hooks", path, apply: () => writeJsonAtomic(path, { ...cfg, hooks: cleaned }) };
}

function skillSteps(root: string, host: string): UninstallStep[] {
  const dirs = BUNDLED_SKILLS.map((name) => join(root, "skills", name)).filter((dir) => existsSync(dir));
  if (dirs.length === 0) return [];
  return [
    {
      what: `${host} skills (${dirs.length}, amem-*)`,
      path: join(root, "skills"),
      apply: () => dirs.forEach((dir) => rmSync(dir, { recursive: true, force: true })),
    },
  ];
}

/** The marked block in this repo's CLAUDE.md, AGENTS.md …; a file amem owns outright goes. */
function instructionSteps(repoRoot: string): UninstallStep[] {
  const steps: UninstallStep[] = [];
  const paths = new Set(allInstructionTargets().map((t) => t.path));
  paths.add(join(".cursor", "rules", "amem.mdc"));
  for (const rel of paths) {
    const full = join(repoRoot, rel);
    if (!existsSync(full)) continue;
    const text = readFileSync(full, "utf8");
    const start = text.indexOf(BEGIN);
    const end = text.indexOf(END);
    if (start !== -1 && end > start) {
      const rest = `${text.slice(0, start)}${text.slice(end + END.length)}`.replace(/\n{3,}/g, "\n\n").trim();
      steps.push({
        what: "amem instructions",
        path: full,
        apply: () => (rest ? writeFileSync(full, `${rest}\n`, "utf8") : rmSync(full, { force: true })),
      });
    } else if (text.includes("Generated by amem")) {
      steps.push({ what: "amem instructions", path: full, apply: () => rmSync(full, { force: true }) });
    }
  }
  return steps;
}

export function planUninstall(opts: { repoRoot?: string; purge?: boolean } = {}): UninstallStep[] {
  const claudeHome = process.env.CLAUDE_HOME ?? join(homedir(), ".claude");
  const cursorHome = process.env.CURSOR_HOME ?? join(homedir(), ".cursor");
  const zedDir =
    process.platform === "darwin" ? join(homedir(), "Library", "Application Support", "Zed") : join(homedir(), ".config", "zed");
  const steps: Array<UninstallStep | null> = [
    claudeHooksStep(),
    serverEntryStep("Claude Code MCP server", claudeUserConfigPath()),
    ...skillSteps(claudeHome, "Claude Code"),
    cursorHooksStep(cursorHome),
    serverEntryStep("Cursor MCP server", join(cursorHome, "mcp.json")),
    ...skillSteps(cursorHome, "Cursor"),
    serverEntryStep("Claude Desktop MCP server", claudeDesktopConfigPath()),
    serverEntryStep("Windsurf MCP server", join(homedir(), ".codeium", "windsurf", "mcp_config.json")),
    serverEntryStep("Zed context server", join(zedDir, "settings.json"), "context_servers"),
  ];
  const continueYaml = join(homedir(), ".continue", "mcpServers", "amem.yaml");
  if (existsSync(continueYaml)) {
    steps.push({ what: "Continue MCP server", path: continueYaml, apply: () => rmSync(continueYaml, { force: true }) });
  }
  if (opts.repoRoot) steps.push(...instructionSteps(opts.repoRoot));
  if (isServiceInstalled()) steps.push({ what: "dashboard login service", path: "", apply: () => void uninstallLoginService() });
  if (isBackupScheduleInstalled()) steps.push({ what: "backup schedule", path: "", apply: () => void uninstallBackupSchedule() });
  if (isHygieneScheduleInstalled()) steps.push({ what: "hygiene schedule", path: "", apply: () => void uninstallHygieneSchedule() });
  if (opts.purge && existsSync(amemHome())) {
    steps.push({ what: "ALL amem memory (cannot be undone)", path: amemHome(), apply: () => rmSync(amemHome(), { recursive: true, force: true }) });
  }
  return steps.filter((s): s is UninstallStep => s !== null);
}
